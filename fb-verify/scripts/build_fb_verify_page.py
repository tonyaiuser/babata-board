def main():
    global UNIQUE_JSON, FULL_VERIFY_JSON, PRODUCT_IMAGES_JSON, OUTPUT_HTML, DASHBOARD_MONTH

    ap = argparse.ArgumentParser()
    ap.add_argument("--unique-json", required=True)
    ap.add_argument("--full-verify-json", required=True)
    ap.add_argument("--images-json", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--view-kind", required=True, choices=("monthly", "batch"))
    ap.add_argument("--group-ids", default="", help="可选，逗号分隔；仅渲染指定产品组")
    ap.add_argument("--view-title", default="")
    ap.add_argument("--view-subtitle", default="")
    cli_args = ap.parse_args()

    UNIQUE_JSON = cli_args.unique_json
    FULL_VERIFY_JSON = cli_args.full_verify_json
    PRODUCT_IMAGES_JSON = cli_args.images_json
    OUTPUT_HTML = cli_args.out
    if cli_args.group_ids == "":
        selected_group_ids = []
    else:
        selected_group_ids = [gid.strip() for gid in cli_args.group_ids.split(",")]
        if any(not gid for gid in selected_group_ids):
            raise SystemExit("--group-ids must not contain empty ids")
        if len(selected_group_ids) != len(set(selected_group_ids)):
            raise SystemExit("--group-ids must not contain duplicate ids")
    if cli_args.view_kind == "monthly" and selected_group_ids:
        raise SystemExit("monthly view forbids --group-ids")
    if cli_args.view_kind == "batch" and not selected_group_ids:
        raise SystemExit("batch view requires non-empty --group-ids")
    DASHBOARD_MONTH = validate_dashboard_paths(
        UNIQUE_JSON, FULL_VERIFY_JSON, PRODUCT_IMAGES_JSON, OUTPUT_HTML, cli_args.view_kind
    )

    records, meta = build_records()
    if selected_group_ids:
        records_by_id = {record["group_id"]: record for record in records}
        missing_group_ids = [gid for gid in selected_group_ids if gid not in records_by_id]
        if missing_group_ids:
            raise SystemExit(
                "--group-ids contains unknown or unavailable ids; refusing to render batch: "
                + ", ".join(missing_group_ids)
            )
        records = [records_by_id[gid] for gid in selected_group_ids]
        meta["unverified_count"] = sum(
            1 for record in records
            if record.get("verification_state") not in {
                "positive", "sample_negative", "explicit_zero"
            }
        )
    # 默认排序：已查到投放的产品按最长投放天数升序；未查到的固定置底。
    # 浏览器端使用同一规则重排，保证页面初始数据与交互后的顺序一致。
    def freshness_sort_key(r):
        days = to_int(r.get("max_run_days"))
        if not r["found"]:
            return (2, float("inf"), 0, 0, r.get("clean_title") or "")
        if days is None:
            return (1, float("inf"), -(r["cross_count"] or 0), -(r["relevant_count"] or 0), r.get("clean_title") or "")
        return (0, days, -(r["cross_count"] or 0), -(r["relevant_count"] or 0), r.get("clean_title") or "")

    records.sort(key=freshness_sort_key)
    batch_view = cli_args.view_kind == "batch"
    view_title = cli_args.view_title or ("本轮 FB 确认产品" if batch_view else DEFAULT_MONTHLY_TITLE)
    view_subtitle = cli_args.view_subtitle or (
        "本次增量验证确认有相关投放的单页产品；产品图可直接打开来源单页。"
        if batch_view else
        DEFAULT_MONTHLY_SUBTITLE
    )
    dashboard_guard = None
    if cli_args.view_kind == "monthly":
        dashboard_guard = _monthly_guard(meta, records)
        # All fail-closed decisions happen before rendering/writing.  The
        # existing page is therefore byte-for-byte intact on every rejection.
        assert_monthly_dashboard_monotonic(OUTPUT_HTML, dashboard_guard)
    html = render_html(
        records, meta, view_title, view_subtitle,
        batch_view=batch_view, dashboard_guard=dashboard_guard,
    )
    atomic_write_bytes(OUTPUT_HTML, html.encode("utf-8"))
    print(f"生成完成: {OUTPUT_HTML}")
    print(f"产品组数: {len(records)}, 查到FB投放: {sum(1 for r in records if r['found'])}, 未验证: {meta.get('unverified_count')}")
    summary = {
        "total_groups": len(records),
        "found": sum(1 for r in records if r["found"]),
        "unverified": meta.get("unverified_count"),
    }
    if batch_view:
        summary.update({
            "requested": selected_group_ids,
            "resolved": [record["group_id"] for record in records],
            "missing": [],
        })
    print("BUILD_SUMMARY_JSON " + json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
