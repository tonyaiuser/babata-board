def clean_title(raw: str) -> str:
    if not raw:
        return ""
    t = EMOJI_PATTERN.sub(" ", raw)
    t = re.sub(r"\d+%\s*(OFF|DE R[ÉE]DUCTION)", " ", t, flags=re.IGNORECASE)
    t = PROMO_WORDS.sub(" ", t)
    t = re.sub(r"[!！]{1,}", "", t)
    t = re.sub(r"^[\s:：\-–|]+", "", t)
    t = re.sub(r"\s{2,}", " ", t).strip(" .:-–|")
    return t or raw.strip()


def load_json(path, default=None):
    if not os.path.exists(path):
        return default
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as exc:
        raise SystemExit(f"persistent state unreadable; refusing to continue {path}: {exc}")
    if not isinstance(data, dict):
        raise SystemExit(f"persistent state has invalid schema; refusing to continue {path}")
    return data


def to_int(v):
    if v is None or isinstance(v, bool):
        return None
    try:
        number = float(v)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(number) or not number.is_integer():
        return None
    return int(number)


def to_finite_number(value, *, minimum=None):
    """Return a JSON-safe finite number, never attacker-controlled text."""
    if value is None or isinstance(value, bool):
        return None
    try:
        number = float(value)
    except (TypeError, ValueError):
        return None
    if not math.isfinite(number) or (minimum is not None and number < minimum):
        return None
    return int(number) if number.is_integer() else number


def normalize_image_url(value):
    if not value or not isinstance(value, str):
        return None
    value = html_lib.unescape(value.strip())
    if value.startswith("//"):
        return "https:" + value
    if value.startswith("http://"):
        value = "https://" + value[len("http://"):]
    try:
        parsed = urlparse(value)
    except ValueError:
        return None
    if parsed.scheme.lower() not in {"http", "https"} or not parsed.netloc:
        return None
    return value


def json_for_script(value):
    """Serialize data safely for an inline ``<script>`` JSON literal."""
    return json.dumps(value, ensure_ascii=False).replace("<", "\\u003c").replace(
        "\u2028", "\\u2028"
    ).replace("\u2029", "\\u2029")


def json_for_html_comment(value):
    """Serialize guard metadata without allowing a group id to close its comment."""
    return json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace(
        "<", "\\u003c"
    ).replace("--", "\\u002d\\u002d")


def _unique_string_ids(values, field):
    """Return a sorted, duplicate-free set of durable group ids."""
    if not isinstance(values, list) or any(
        not isinstance(value, str) or not value.strip() for value in values
    ):
        raise ValueError(f"{field} must be an array of non-empty strings")
    if len(values) != len(set(values)):
        raise ValueError(f"{field} must not contain duplicate ids")
    return sorted(values)


def parse_calendar_month(value, field):
    if not isinstance(value, str) or not MONTH_PATTERN.fullmatch(value):
        raise ValueError(f"{field} must use YYYY-MM")
    try:
        parsed = datetime.strptime(value, "%Y-%m")
    except ValueError as exc:
        raise ValueError(f"{field} is not a valid calendar month") from exc
    if parsed.strftime("%Y-%m") != value:
        raise ValueError(f"{field} is not a canonical calendar month")
    return value


def validate_dashboard_paths(unique_json, verify_json, images_json, output_html, view_kind):
    """Bind every monthly input and output to one explicit calendar month."""
    inputs = [Path(path).resolve() for path in (unique_json, verify_json, images_json)]
    input_parent = inputs[0].parent
    if any(path.parent != input_parent for path in inputs[1:]):
        raise SystemExit("dashboard JSON inputs must share the same monthly directory")
    try:
        month = parse_calendar_month(input_parent.name, "dashboard input directory")
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc

    output = Path(output_html).resolve()
    if view_kind == "monthly":
        if output.parent != input_parent or output.name != "fb_verify_dashboard.html":
            raise SystemExit(
                "monthly dashboard output must be <input-month>/fb_verify_dashboard.html"
            )
    else:
        if (
            output.name == "fb_verify_dashboard.html"
            or output.parent.name != "batches"
            or output.parent.parent != input_parent
        ):
            raise SystemExit(
                "batch output must be <input-month>/batches/<non-canonical-name>.html"
            )

    unique = load_json(str(inputs[0]))
    try:
        stated = parse_calendar_month(unique.get("month"), "unique products month")
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc
    if stated != month:
        raise SystemExit(
            "unique products month disagrees with dashboard input directory; refusing to build"
        )
    return month


def _json_sha256(value):
    try:
        payload = json.dumps(
            value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False
        ).encode("utf-8")
    except (TypeError, ValueError) as exc:
        raise ValueError(f"state is not canonical JSON: {exc}") from exc
    return hashlib.sha256(payload).hexdigest()


def _id_mapping(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    result = {}
    for source, target in value.items():
        if not isinstance(source, str) or not source.strip():
            raise ValueError(f"{field} keys must be non-empty strings")
        if not isinstance(target, str) or not target.strip():
            raise ValueError(f"{field} targets must be non-empty strings")
        if source == target:
            raise ValueError(f"{field} cannot contain a self-alias")
        result[source] = target
    return result


def _sha_mapping(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    if any(
        not isinstance(key, str) or not key.strip()
        or not isinstance(digest, str) or not SHA256_PATTERN.fullmatch(digest)
        for key, digest in value.items()
    ):
        raise ValueError(f"{field} must map non-empty ids to sha256 digests")
    return dict(value)


def _checkpoint_provenance(record, field):
    raw = record.get("merged_from", [])
    if not isinstance(raw, list):
        raise ValueError(f"{field} must be an array")
    return _unique_string_ids(raw, field)


def _provenance_mapping(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    result = {}
    for gid, sources in value.items():
        if not isinstance(gid, str) or not gid.strip():
            raise ValueError(f"{field} keys must be non-empty strings")
        normalized = _unique_string_ids(sources, f"{field} for {gid}")
        if sources != normalized:
            raise ValueError(f"{field} for {gid} must be sorted canonically")
        result[gid] = normalized
    return result


def _immutable_checkpoint_evidence_sha256(gid, record):
    """Hash every checkpoint field except its audited merge provenance list."""
    immutable = dict(record)
    immutable.pop("merged_from", None)
    # The merge producer materializes these implicit self-identities. Treating
    # an absent value as self makes that serialization-only change canonical;
    # selecting another group's evidence still changes evidence_group_id.
    immutable.setdefault("group_id", gid)
    immutable.setdefault("evidence_group_id", gid)
    return _json_sha256(immutable)


def _member_mapping(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    result = {}
    for gid, members in value.items():
        if not isinstance(gid, str) or not gid.strip() or not isinstance(members, list):
            raise ValueError(f"{field} entries are invalid")
        pairs = []
        for member in members:
            if (
                not isinstance(member, list) or len(member) != 2
                or any(not isinstance(part, str) or not part for part in member)
            ):
                raise ValueError(f"{field} member identities must be [domain, handle]")
            pairs.append(tuple(member))
        if len(pairs) != len(set(pairs)):
            raise ValueError(f"{field} contains duplicate member identities")
        result[gid] = sorted(pairs)
    return result


def _positive_evidence_ids(record):
    evidence = []
    for ad in record.get("relevant_ads") or []:
        if not isinstance(ad, dict):
            continue
        archive_id = ad.get("ad_archive_id")
        simple_id = ad.get("id")
        if archive_id not in (None, ""):
            evidence.append(f"archive:{archive_id}")
        if simple_id not in (None, ""):
            evidence.append(f"id:{simple_id}")
        # Keep independent fallback identities as well as a newly discovered
        # archive id. Enriching an existing ad with more fields then preserves
        # its prior body/link identity instead of looking like evidence loss.
        for field in ("link_url", "body", "title", "caption"):
            value = ad.get(field)
            if value not in (None, ""):
                evidence.append(f"{field}:" + _json_sha256(str(value)))
        if archive_id in (None, "") and simple_id in (None, "") and not any(
            ad.get(field) not in (None, "") for field in ("link_url", "body", "title", "caption")
        ):
            stable = {
                field: ad.get(field)
                for field in ("advertiser", "page_id", "start_date")
                if ad.get(field) not in (None, "")
            }
            if stable:
                evidence.append("content:" + _json_sha256(stable))
    return sorted(set(evidence))


def build_checkpoint_semantics(alias_contract, full_verify):
    """Capture only transition invariants, leaving retry diagnostics mutable."""
    verify_groups = full_verify["groups"]
    archive = full_verify.get("checkpoint_archive", {})
    aliases = alias_contract["checkpoint_aliases"]
    archived_by_terminal = {}
    for source in aliases:
        archived = archive.get(source)
        if not isinstance(archived, dict):
            continue
        try:
            normalized = migrate_verification_record(archived)
        except ValueError as exc:
            raise ValueError(f"checkpoint archive {source} is invalid: {exc}") from exc
        terminal = _resolve_alias(source, aliases, field="checkpoint_aliases")
        archived_by_terminal.setdefault(terminal, []).append(normalized)

    semantics = {}
    for gid in alias_contract["active_group_ids"]:
        record = verify_groups.get(gid)
        if record is None:
            semantics[gid] = {
                "state": "missing", "positive_relevant_floor": 0,
                "positive_evidence_ids": [],
            }
            continue
        state = record.get("verification_state") or "inconclusive"
        positive_records = [record] if state == "positive" else []
        positive_records.extend(
            archived_record for archived_record in archived_by_terminal.get(gid, [])
            if archived_record.get("verification_state") == "positive"
        )
        evidence = sorted({
            evidence_id
            for positive_record in positive_records
            for evidence_id in _positive_evidence_ids(positive_record)
        })
        floor = max(
            [int(positive_record.get("relevant_ads_count") or 0) for positive_record in positive_records]
            or [0]
        )
        semantics[gid] = {
            "state": state,
            "positive_relevant_floor": floor,
            "positive_evidence_ids": evidence,
        }
    return semantics


def _semantic_mapping(value, field):
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    allowed = {"missing", "positive", "sample_negative", "explicit_zero", "inconclusive"}
    result = {}
    for gid, semantic in value.items():
        if not isinstance(gid, str) or not gid.strip() or not isinstance(semantic, dict):
            raise ValueError(f"{field} entries are invalid")
        state = semantic.get("state")
        floor = semantic.get("positive_relevant_floor")
        evidence = semantic.get("positive_evidence_ids")
        if state not in allowed:
            raise ValueError(f"{field} has an invalid state for {gid}")
        if isinstance(floor, bool) or not isinstance(floor, int) or floor < 0:
            raise ValueError(f"{field} has an invalid positive floor for {gid}")
        evidence = _unique_string_ids(evidence, f"{field} positive evidence for {gid}")
        if state == "positive" and (floor <= 0 or not evidence):
            raise ValueError(f"{field} positive state lacks durable relevant_ads evidence for {gid}")
        result[gid] = {
            "state": state,
            "positive_relevant_floor": floor,
            "positive_evidence_ids": evidence,
        }
    return result


def _resolve_alias(source, aliases, *, field):
    seen = set()
    current = source
    while current in aliases:
        if current in seen:
            raise ValueError(f"{field} contains an alias cycle")
        seen.add(current)
        current = aliases[current]
    return current


def _alias_entry_mapping(value, field):
    if value is None:
        return {}
    if not isinstance(value, dict):
        raise ValueError(f"{field} must be an object")
    result = {}
    for source, entry in value.items():
        if not isinstance(source, str) or not source.strip() or not isinstance(entry, dict):
            raise ValueError(f"{field} entries must be keyed objects")
        target = entry.get("canonical_group_id")
        if not isinstance(target, str) or not target.strip() or target == source:
            raise ValueError(f"{field} has an invalid canonical_group_id for {source}")
        if entry.get("reason") != "duplicate_merged_into":
            raise ValueError(f"{field} has an invalid reason for {source}")
        result[source] = target
    return result


def _merged_from_contains(record, source, field):
    merged_from = record.get("merged_from")
    if not isinstance(merged_from, list) or any(
        not isinstance(value, str) or not value.strip() for value in merged_from
    ):
        raise ValueError(f"{field} must have a string merged_from audit list")
    if source not in merged_from:
        raise ValueError(f"{field} merged_from does not include {source}")


def _alias_reaches_target(source, target, aliases):
    """Return whether source's validated alias chain passes through target."""
    current = source
    seen = set()
    while current in aliases:
        if current in seen:
            raise ValueError("group_aliases contains an alias cycle")
        seen.add(current)
        current = aliases[current]
        if current == target:
            return True
    return False


def _validate_group_merge_provenance(by_gid, group_aliases):
    """Bind each alias target to its exact canonical/descendant provenance."""
    for target in sorted(set(group_aliases.values())):
        expected = sorted({
            target,
            *(
                source for source in group_aliases
                if _alias_reaches_target(source, target, group_aliases)
            ),
        })
        raw = by_gid[target].get("merged_from")
        if not isinstance(raw, list):
            raise ValueError(
                f"group merge provenance for {target} must be a canonical string list"
            )
        actual = _unique_string_ids(raw, f"group merge provenance for {target}")
        if raw != actual or actual != expected:
            raise ValueError(
                f"group merge provenance for {target} must exactly equal {expected}"
            )


def validate_alias_contract(unique, full_verify):
    """Validate that every quarantine is a lossless, convergent alias."""
    groups = unique["groups"]
    by_gid = {group["group_id"]: group for group in groups}
    group_aliases = _alias_entry_mapping(unique.get("group_aliases"), "group_aliases")
    quarantined = set()
    member_keys = {}
    for gid, group in by_gid.items():
        if "quarantined" in group and not isinstance(group["quarantined"], bool):
            raise ValueError(f"group {gid} quarantined flag must be boolean")
        members = group.get("members")
        if not isinstance(members, list) or any(not isinstance(member, dict) for member in members):
            raise ValueError(f"group {gid} members must be an array of objects")
        keys = set()
        for member in members:
            domain, handle = member.get("domain"), member.get("handle")
            if not isinstance(domain, str) or not domain or not isinstance(handle, str) or not handle:
                raise ValueError(f"group {gid} member identity is incomplete")
            keys.add((domain, handle))
        member_keys[gid] = keys
        if group.get("quarantined"):
            quarantined.add(gid)

    if quarantined != set(group_aliases):
        raise ValueError("quarantined groups and group_aliases must match exactly")
    active = set(by_gid) - quarantined
    for source, target in group_aliases.items():
        source_group = by_gid.get(source)
        target_group = by_gid.get(target)
        if target_group is None:
            raise ValueError(f"group alias {source} points to missing group {target}")
        if (
            source_group.get("quarantine_reason") != "duplicate_merged_into"
            or source_group.get("merged_into") != target
        ):
            raise ValueError(f"quarantined group {source} disagrees with group_aliases")
        if not member_keys[source].issubset(member_keys[target]):
            raise ValueError(f"group alias {source}->{target} loses product members")
        terminal = _resolve_alias(source, group_aliases, field="group_aliases")
        if terminal not in active:
            raise ValueError(f"group alias {source} does not converge to an active group")
    _validate_group_merge_provenance(by_gid, group_aliases)

    verify_groups = full_verify["groups"]
    raw_archive = full_verify.get("checkpoint_archive", {})
    if not isinstance(raw_archive, dict) or any(
        not isinstance(gid, str) or not gid.strip() or not isinstance(record, dict)
        for gid, record in raw_archive.items()
    ):
        raise ValueError("checkpoint_archive must map group ids to evidence objects")
    checkpoint_aliases = _alias_entry_mapping(
        full_verify.get("checkpoint_aliases"), "checkpoint_aliases"
    )
    quarantined_checkpoints = {
        gid for gid, record in verify_groups.items() if record.get("quarantined") is True
    }
    if quarantined_checkpoints != set(checkpoint_aliases):
        raise ValueError("quarantined checkpoints and checkpoint_aliases must match exactly")
    for source, target in checkpoint_aliases.items():
        source_record = verify_groups.get(source)
        target_record = verify_groups.get(target)
        if source not in group_aliases or group_aliases[source] != target:
            raise ValueError(f"checkpoint alias {source}->{target} disagrees with group alias")
        if source not in raw_archive:
            raise ValueError(f"checkpoint alias {source} has no archived evidence")
        if target_record is None:
            raise ValueError(f"checkpoint alias {source} points to missing checkpoint {target}")
        if (
            source_record.get("quarantine_reason") != "duplicate_merged_into"
            or source_record.get("merged_into") != target
        ):
            raise ValueError(f"quarantined checkpoint {source} disagrees with checkpoint_aliases")
        _merged_from_contains(target_record, source, f"checkpoint alias target {target}")
        checkpoint_terminal = _resolve_alias(source, checkpoint_aliases, field="checkpoint_aliases")
        group_terminal = _resolve_alias(source, group_aliases, field="group_aliases")
        if checkpoint_terminal != group_terminal or checkpoint_terminal not in verify_groups:
            raise ValueError(f"checkpoint alias {source} does not converge with its group alias")

    checkpoint_provenance = {
        gid: _checkpoint_provenance(record, f"checkpoint {gid} merged_from")
        for gid, record in verify_groups.items()
    }
    for gid, sources in checkpoint_provenance.items():
        expected_sources = sorted(
            source for source, target in checkpoint_aliases.items() if target == gid
        )
        if sources != expected_sources:
            raise ValueError(
                f"checkpoint {gid} merged_from provenance does not exactly match aliases"
            )

    return {
        "all_group_ids": sorted(by_gid),
        "active_group_ids": sorted(active),
        "quarantined_group_ids": sorted(quarantined),
        "group_members": {
            gid: [list(pair) for pair in sorted(member_keys[gid])] for gid in sorted(by_gid)
        },
        "group_aliases": group_aliases,
        "checkpoint_aliases": checkpoint_aliases,
        "checkpoint_evidence_sha256": {
            gid: _json_sha256(record) for gid, record in verify_groups.items()
        },
        "checkpoint_immutable_evidence_sha256": {
            gid: _immutable_checkpoint_evidence_sha256(gid, record)
            for gid, record in verify_groups.items()
        },
        "checkpoint_merged_from": checkpoint_provenance,
        "checkpoint_archive_sha256": {
            gid: _json_sha256(record) for gid, record in raw_archive.items()
        },
    }


def validate_month_bound_build_state(unique, full_verify, expected_month):
    if expected_month is None:
        return
    try:
        if parse_calendar_month(unique.get("month"), "unique products month") != expected_month:
            raise ValueError("unique products month disagrees with build month")
        if parse_calendar_month(full_verify.get("month"), "checkpoint month") != expected_month:
            raise ValueError("checkpoint month disagrees with build month")
        for container_name, container in (
            ("unique groups", {group["group_id"]: group for group in unique["groups"]}),
            ("checkpoint groups", full_verify["groups"]),
            ("checkpoint archive", full_verify.get("checkpoint_archive", {})),
        ):
            if not isinstance(container, dict):
                raise ValueError(f"{container_name} must be an object")
            for gid, record in container.items():
                if parse_calendar_month(
                    record.get("state_month"), f"{container_name} state_month"
                ) != expected_month:
                    raise ValueError(f"{container_name} record {gid} is bound to another month")
    except (KeyError, TypeError, ValueError) as exc:
        raise SystemExit(
            f"monthly state binding is invalid; refusing to build dashboard: {exc}"
        ) from exc


def _extract_embedded_records(page_body):
    """Parse only the exact script structure emitted by this builder."""
    if (
        not page_body.startswith('<!DOCTYPE html>\n<html lang="zh-CN">\n<head>')
        or not page_body.endswith("</html>\n")
        or page_body.count("<script>") != 1
        or page_body.count("</script>") != 1
        or page_body.count("<title>单页产品 × FB 投放验证</title>") != 1
    ):
        raise ValueError("page skeleton does not match a monthly dashboard")
    records_prefix = "\n<script>\nconst RECORDS = "
    sort_prefix = ";\nconst SORT_DEFAULT_DIRECTIONS = "
    if (
        page_body.count(records_prefix) != 1
        or page_body.count(sort_prefix) != 1
        or len(re.findall(r"(?m)^const RECORDS = ", page_body)) != 1
        or len(re.findall(r"(?m)^const SORT_DEFAULT_DIRECTIONS = ", page_body)) != 1
    ):
        raise ValueError("page must contain exactly one canonical RECORDS script")
    start = page_body.index(records_prefix) + len(records_prefix)
    try:
        records, consumed = json.JSONDecoder().raw_decode(page_body[start:])
    except json.JSONDecodeError as exc:
        raise ValueError(f"embedded RECORDS is invalid: {exc}") from exc
    if not page_body.startswith(sort_prefix, start + consumed):
        raise ValueError("embedded RECORDS is not followed by the canonical sort script")
    if not isinstance(records, list):
        raise ValueError("embedded RECORDS is not an array")
    return records


def _assert_exact_legacy_artifact(page_body, records):
    """Require a byte-exact reproduction of the complete pre-guard artifact."""
    prefix = '<div class="generated-at">生成时间：'
    matches = re.findall(re.escape(prefix) + r"(.*?)</div>", page_body, flags=re.DOTALL)
    if len(matches) != 1:
        raise ValueError("legacy dashboard has no unique generated-at field")
    raw_generated_at = matches[0]
    if raw_generated_at:
        if not LEGACY_GENERATED_AT_PATTERN.fullmatch(raw_generated_at):
            raise ValueError("legacy dashboard generated-at is not a canonical timestamp")
        try:
            parsed_generated_at = datetime.fromisoformat(
                raw_generated_at[:-1] + "+00:00"
                if raw_generated_at.endswith("Z") else raw_generated_at
            )
        except ValueError as exc:
            raise ValueError("legacy dashboard generated-at is not a real timestamp") from exc
        if parsed_generated_at.utcoffset() is None:
            raise ValueError("legacy dashboard generated-at must include a timezone")
    generated_at = raw_generated_at
    meta = {
        "generated_at": generated_at,
        "unverified_count": sum(
            1 for record in records
            if record.get("verification_state") not in {
                "positive", "sample_negative", "explicit_zero"
            }
        ),
    }
    try:
        expected = render_html(
            records, meta, DEFAULT_MONTHLY_TITLE, DEFAULT_MONTHLY_SUBTITLE,
            batch_view=False, dashboard_guard=None,
        )
    except (KeyError, TypeError, ValueError) as exc:
        raise ValueError(f"legacy RECORDS lacks the complete builder schema: {exc}") from exc
    if expected == page_body:
        return

    total = len(records)
    expected_counts = [
        total,
        sum(1 for record in records if record.get("found")),
        sum(
            1 for record in records
            if record.get("found") and to_int(record.get("max_run_days")) is not None
            and to_int(record.get("max_run_days")) <= 7
        ),
        sum(
            1 for record in records
            if record.get("found") and (to_int(record.get("cross_count")) or 0) >= 3
        ),
        sum(1 for record in records if (to_int(record.get("member_count")) or 0) >= 2),
        total - sum(1 for record in records if record.get("found")),
    ]
    stats_start_token = '<div class="stats-row">'
    stats_end_token = '\n    </div>\n  </div>\n</div>\n\n<div class="controls">'
    if page_body.count(stats_start_token) != 1 or page_body.count(stats_end_token) != 1:
        raise ValueError("legacy dashboard has no canonical stats block")
    stats_start = page_body.index(stats_start_token) + len(stats_start_token)
    stats_end = page_body.index(stats_end_token, stats_start)
    stats_body = page_body[stats_start:stats_end]
    actual_counts = [
        int(value) for value in re.findall(
            r'<div class="stat-pill"><strong>([0-9]+)</strong>[^<]+</div>',
            stats_body,
        )
    ]
    if actual_counts != expected_counts:
        raise ValueError("legacy dashboard counters disagree with embedded RECORDS")
    result_counts = re.findall(
        r'<span class="count" id="result-count">([0-9]+)</span>', page_body
    )
    if result_counts != [str(total)]:
        raise ValueError("legacy dashboard result count disagrees with embedded RECORDS")

    records_prefix = "\n<script>\nconst RECORDS = "
    start = page_body.index(records_prefix) + len(records_prefix)
    _, consumed = json.JSONDecoder().raw_decode(page_body[start:])
    normalized = page_body[:start] + "<RECORDS>" + page_body[start + consumed:]
    normalized, generated_replacements = re.subn(
        r'(<div class="generated-at">生成时间：).*?(</div>)',
        r'\1<GENERATED>\2', normalized, flags=re.DOTALL,
    )
    normalized, stat_replacements = re.subn(
        r'(<div class="stat-pill"><strong>)[0-9]+(</strong>)',
        r'\1<N>\2', normalized,
    )
    normalized, result_replacements = re.subn(
        r'(<span class="count" id="result-count">)[0-9]+(</span>)',
        r'\1<N>\2', normalized,
    )
    if (generated_replacements, stat_replacements, result_replacements) != (1, 6, 1):
        raise ValueError("legacy dashboard dynamic slots are not canonical")
    fingerprint = hashlib.sha256(normalized.encode("utf-8")).hexdigest()
    if fingerprint not in TRUSTED_LEGACY_TEMPLATE_SHA256:
        raise ValueError("legacy dashboard template fingerprint is unknown")


def _legacy_record_contract(records):
    members = {}
    semantics = {}
    for record in records:
        gid = record["group_id"]
        member_pairs = []
        for member in record.get("members") or []:
            domain, handle = member.get("domain"), member.get("handle")
            if not isinstance(domain, str) or not domain or not isinstance(handle, str) or not handle:
                raise ValueError(f"legacy group {gid} has an incomplete member identity")
            member_pairs.append((domain, handle))
        if len(member_pairs) != len(set(member_pairs)):
            raise ValueError(f"legacy group {gid} has duplicate members")
        members[gid] = sorted(member_pairs)

        recorded_state = record.get("verification_state")
        if recorded_state is not None and recorded_state not in {
            "missing", "positive", "sample_negative", "explicit_zero", "inconclusive",
        }:
            raise ValueError(f"legacy group {gid} has an invalid verification state")
        legacy_fb_total = to_int(record.get("fb_total"))
        if recorded_state == "positive" or (
            recorded_state is None and record.get("found") is True
        ):
            evidence = []
            for ad in record.get("ad_samples") or []:
                library_url = ad.get("fb_lib_url") if isinstance(ad, dict) else None
                if isinstance(library_url, str):
                    match = re.search(r"[?&]id=([^&#]+)", library_url)
                    if match:
                        evidence.append("archive:" + match.group(1))
            floor = to_int(record.get("relevant_count")) or 0
            if floor <= 0 or not evidence:
                raise ValueError(f"legacy positive group {gid} lacks durable ad evidence")
            semantics[gid] = {
                "state": "positive", "positive_relevant_floor": floor,
                "positive_evidence_ids": sorted(set(evidence)),
            }
        elif recorded_state in {"sample_negative", "explicit_zero"}:
            semantics[gid] = {
                "state": recorded_state, "positive_relevant_floor": 0,
                "positive_evidence_ids": [],
            }
        elif recorded_state in {"missing", "inconclusive"}:
            semantics[gid] = {
                "state": recorded_state, "positive_relevant_floor": 0,
                "positive_evidence_ids": [],
            }
        elif (
            recorded_state is None
            and record.get("found") is False
            and record.get("verify_error") in (None, "")
            and legacy_fb_total is not None
            and legacy_fb_total >= 0
        ):
            # The pre-four-state page did not distinguish explicit zero from a
            # sampled negative, but a numeric FB result proves that a response
            # was processed. A null fb_total does not: historical pages used
            # found=false/verify_error=null for some groups that had never run.
            semantics[gid] = {
                "state": "terminal_negative_unknown", "positive_relevant_floor": 0,
                "positive_evidence_ids": [],
            }
        else:
            semantics[gid] = {
                "state": "unverified", "positive_relevant_floor": 0,
                "positive_evidence_ids": [],
            }
    return members, semantics


def _guard_from_existing_page(output_html):
    """Read a prior healthy dashboard baseline without modifying it.

    Older pages have no guard marker.  Their embedded RECORDS array is enough
    to preserve the active groups; checkpoint coverage was not recorded by
    those versions, so only newer guarded pages can enforce that extra check.
    Unknown non-empty files are deliberately not overwritten.
    """
    target = Path(output_html)
    if not target.exists():
        return None
    if not target.is_file():
        raise SystemExit(f"dashboard output is not a regular file: {target}")
    try:
        source = target.read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise SystemExit(f"existing dashboard unreadable; refusing to overwrite {target}: {exc}") from exc

    guard = None
    page_body = source
    if source.startswith(DASHBOARD_GUARD_PREFIX):
        if source.count(DASHBOARD_GUARD_PREFIX) != 1:
            raise SystemExit(
                f"existing dashboard contains multiple guard markers; refusing to overwrite {target}"
            )
        marker_end = source.find(DASHBOARD_GUARD_SUFFIX + "\n", len(DASHBOARD_GUARD_PREFIX))
        if marker_end < 0:
            raise SystemExit(
                f"existing dashboard guard is unterminated; refusing to overwrite {target}"
            )
        encoded_guard = source[len(DASHBOARD_GUARD_PREFIX):marker_end]
        page_body = source[marker_end + len(DASHBOARD_GUARD_SUFFIX) + 1:]
        try:
            guard = json.loads(encoded_guard)
            if not isinstance(guard, dict):
                raise ValueError("guard is not an object")
            guard_schema_version = guard.get("schema_version")
            if guard_schema_version not in {
                LEGACY_DASHBOARD_GUARD_SCHEMA_VERSION,
                DASHBOARD_GUARD_SCHEMA_VERSION,
            }:
                raise ValueError("unsupported guard schema")
            if guard.get("kind") != "monthly":
                raise ValueError("guard is not a monthly dashboard")
            month = parse_calendar_month(guard.get("month"), "guard month")
            active_ids = _unique_string_ids(guard.get("active_group_ids"), "guard active_group_ids")
            all_ids = _unique_string_ids(guard.get("all_group_ids"), "guard all_group_ids")
            quarantined_ids = _unique_string_ids(
                guard.get("quarantined_group_ids"), "guard quarantined_group_ids"
            )
            group_members = _member_mapping(guard.get("group_members"), "guard group_members")
            checkpoint_ids = _unique_string_ids(
                guard.get("checkpoint_group_ids"), "guard checkpoint_group_ids"
            )
            group_aliases = _id_mapping(guard.get("group_aliases"), "guard group_aliases")
            checkpoint_aliases = _id_mapping(
                guard.get("checkpoint_aliases"), "guard checkpoint_aliases"
            )
            evidence_hashes = _sha_mapping(
                guard.get("checkpoint_evidence_sha256"), "guard checkpoint_evidence_sha256"
            )
            immutable_evidence_hashes = None
            checkpoint_provenance = None
            if guard_schema_version == DASHBOARD_GUARD_SCHEMA_VERSION:
                immutable_evidence_hashes = _sha_mapping(
                    guard.get("checkpoint_immutable_evidence_sha256"),
                    "guard checkpoint_immutable_evidence_sha256",
                )
                checkpoint_provenance = _provenance_mapping(
                    guard.get("checkpoint_merged_from"),
                    "guard checkpoint_merged_from",
                )
            archive_hashes = _sha_mapping(
                guard.get("checkpoint_archive_sha256"), "guard checkpoint_archive_sha256"
            )
            checkpoint_semantics = _semantic_mapping(
                guard.get("checkpoint_semantics"), "guard checkpoint_semantics"
            )
            records_digest = guard.get("records_sha256")
            if not isinstance(records_digest, str) or not SHA256_PATTERN.fullmatch(records_digest):
                raise ValueError("guard records_sha256 is invalid")
            record_count = guard.get("record_count")
            if isinstance(record_count, bool) or not isinstance(record_count, int) or record_count < 0:
                raise ValueError("invalid guard record_count")
            if record_count != len(active_ids):
                raise ValueError("guard record_count does not match active_group_ids")
            if set(active_ids) | set(quarantined_ids) != set(all_ids):
                raise ValueError("guard active/quarantined ids do not partition all_group_ids")
            if set(group_members) != set(all_ids):
                raise ValueError("guard group_members does not match all_group_ids")
            if set(evidence_hashes) != set(checkpoint_ids):
                raise ValueError("guard checkpoint evidence does not match checkpoint ids")
            if immutable_evidence_hashes is not None and (
                set(immutable_evidence_hashes) != set(checkpoint_ids)
                or set(checkpoint_provenance) != set(checkpoint_ids)
            ):
                raise ValueError(
                    "guard immutable checkpoint metadata does not match checkpoint ids"
                )
            if set(checkpoint_semantics) != set(active_ids):
                raise ValueError("guard checkpoint semantics does not match active groups")
            if set(group_aliases) != set(quarantined_ids):
                raise ValueError("guard aliases do not match quarantined groups")
            for source in group_aliases:
                terminal = _resolve_alias(source, group_aliases, field="guard group_aliases")
                if source not in set(all_ids) or terminal not in set(active_ids):
                    raise ValueError("guard group alias does not converge to an active group")
            for source, target_id in checkpoint_aliases.items():
                if (
                    group_aliases.get(source) != target_id
                    or source not in set(checkpoint_ids)
                    or target_id not in set(checkpoint_ids)
                    or source not in archive_hashes
                ):
                    raise ValueError("guard checkpoint alias is not evidence-conserving")
                if _resolve_alias(source, checkpoint_aliases, field="guard checkpoint_aliases") != _resolve_alias(
                    source, group_aliases, field="guard group_aliases"
                ):
                    raise ValueError("guard checkpoint/group aliases do not converge together")
        except (ValueError, json.JSONDecodeError) as exc:
            raise SystemExit(
                f"existing dashboard guard is invalid; refusing to overwrite {target}: {exc}"
            ) from exc
    elif DASHBOARD_GUARD_PREFIX in source:
        raise SystemExit(
            f"existing dashboard has a non-canonical guard marker; refusing to overwrite {target}"
        )

    try:
        records = _extract_embedded_records(page_body)
        page_active_ids = _unique_string_ids(
            [record.get("group_id") if isinstance(record, dict) else None for record in records],
            "dashboard RECORDS group ids",
        )
    except ValueError as exc:
        raise SystemExit(
            f"existing dashboard is not a recognized healthy monthly page; refusing to overwrite {target}: {exc}"
        ) from exc

    if guard is None:
        try:
            _assert_exact_legacy_artifact(page_body, records)
            legacy_members, legacy_semantics = _legacy_record_contract(records)
        except ValueError as exc:
            raise SystemExit(
                f"existing legacy dashboard is not a trusted complete artifact; "
                f"refusing to overwrite {target}: {exc}"
            ) from exc
        return {
            "source": "legacy",
            "month": None,
            "all_group_ids": None,
            "active_group_ids": page_active_ids,
            "quarantined_group_ids": None,
            "group_aliases": None,
            "group_members": legacy_members,
            "checkpoint_group_ids": None,
            "checkpoint_aliases": None,
            "checkpoint_evidence_sha256": None,
            "checkpoint_immutable_evidence_sha256": None,
            "checkpoint_merged_from": None,
            "checkpoint_archive_sha256": None,
            "checkpoint_semantics": legacy_semantics,
            "record_count": len(page_active_ids),
        }
    if page_active_ids != active_ids or _json_sha256(records) != records_digest:
        raise SystemExit(
            f"existing dashboard guard disagrees with embedded RECORDS; refusing to overwrite {target}"
        )
    return {
        "source": "guarded",
        "month": month,
        "all_group_ids": all_ids,
        "active_group_ids": active_ids,
        "quarantined_group_ids": quarantined_ids,
        "group_aliases": group_aliases,
        "group_members": group_members,
        "checkpoint_group_ids": checkpoint_ids,
        "checkpoint_aliases": checkpoint_aliases,
        "checkpoint_evidence_sha256": evidence_hashes,
        "checkpoint_immutable_evidence_sha256": immutable_evidence_hashes,
        "checkpoint_merged_from": checkpoint_provenance,
        "checkpoint_archive_sha256": archive_hashes,
        "checkpoint_semantics": checkpoint_semantics,
        "record_count": record_count,
    }


